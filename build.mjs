// Builds the generated parts of the static website from the app's own source, so both always agree:
//  • m/codec.js + m/pako_inflate.min.js — the menu-QR reader (same code the app uses to write it)
//  • privacy.html, terms.html, refund.html — from src/legal.js (the same text the app shows offline)
// Run: node website/build.mjs   (tests/menuqr.test.mjs fails if the copies are out of date)
import { copyFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { join, dirname } from 'node:path';
const root = join(dirname(fileURLToPath(import.meta.url)), '..');
copyFileSync(join(root, 'src/utils/menuCodecCore.js'), join(root, 'website/m/codec.js'));
copyFileSync(join(root, 'node_modules/pako/dist/pako_inflate.min.js'), join(root, 'website/m/pako_inflate.min.js'));

const { LEGAL, LEGAL_ORDER, LEGAL_UPDATED } = await import(pathToFileURL(join(root, 'src/legal.js')).href);
const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
const md = (s) => esc(s).replace(/\*\*(.+?)\*\*/g, '<b>$1</b>')
  .replace(/([\w.+-]+@[\w-]+\.[\w.]+)/g, '<a href="mailto:$1">$1</a>')
  .replace(/\bRefund Policy\b/g, '<a href="/refund.html">Refund Policy</a>')
  .replace(/\bthe Terms\b/g, 'the <a href="/terms.html">Terms</a>')
  .replace(/rasoione\.shop\/delete-data\.html/g, '<a href="/delete-data.html">rasoione.shop/delete-data.html</a>');
const files = { privacy: 'privacy.html', terms: 'terms.html', refund: 'refund.html' };
const foot = '<footer class="site"><a href="/">Home</a><a href="/privacy.html">Privacy</a><a href="/terms.html">Terms</a><a href="/refund.html">Refunds</a><a href="/delete-data.html">Delete my data</a></footer>';
for (const id of LEGAL_ORDER) {
  const d = LEGAL[id];
  const body = d.sections.map((s, i) => `  <h2>${i + 1}. ${esc(s.h)}</h2>\n` + (s.p ? `  <p>${md(s.p)}</p>\n` : '') + (s.list ? `  <ul>${s.list.map((x) => `<li>${md(x)}</li>`).join('')}</ul>\n` : '')).join('\n');
  writeFileSync(join(root, 'website', files[id]), `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>${esc(d.title)} · RasoiOne</title>
<link rel="stylesheet" href="/site.css">
</head>
<body>
<!-- Generated by website/build.mjs from src/legal.js — edit that file, not this one. -->
<div class="wrap narrow doc">
  <nav class="site"><a class="logo" href="/">Rasoi<span>One</span></a><div class="links"><a href="/privacy.html">Privacy</a><a href="/terms.html">Terms</a><a href="/refund.html">Refunds</a></div></nav>
  <h1>${esc(d.title)}</h1>
  <p class="eff">Last updated: ${LEGAL_UPDATED} · ${esc(d.scope)}</p>
  <div class="box"><b>In short:</b> ${md(d.summary)}</div>

${body}
  ${foot}
</div>
</body>
</html>
`);
}
console.log('website: codec, privacy, terms, refund updated');
